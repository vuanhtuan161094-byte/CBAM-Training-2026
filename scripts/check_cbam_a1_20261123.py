#!/usr/bin/env python3
"""A1: selected 2025/2547 Annex II-IV technical/transcription regression checks.

Tests verify source declaration, legal field identity, CSV row/units, and formula
symbols. They do NOT prove full official-language equivalence or certify CTIC law.
"""
from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = "ACT-2025-2547"
P0_SHA = "6ca80e3ed665e47aaef801e59e0791c50287ca46db20aad046e861134608ccf7"
WATERMARK = "BẢN DỊCH THAM KHẢO — CHỜ HIỆU ĐÍNH — KHÔNG PHẢI VĂN BẢN CHÍNH THỨC CỦA EU"
DOCS = [
    "translations/vi/REG_2025_2547_annexII_E_F_precursor_activity_vi.md",
    "translations/vi/REG_2025_2547_annexIII_A_attribution_eq41_64_vi.md",
    "translations/vi/REG_2025_2547_annexIV_OER_full_outline_vi.md",
    "translations/vi/REG_2025_2547_annexII_B7_2_B9_2_3_PFC_CKD_vi.md",
]
CSVS = [
    "translations/data/REG_2025_2547_ANNEXII_G_TABLES1_6.csv",
    "translations/data/REG_2025_2547_ANNEXIV_SECTOR_OER_FIELDS.csv",
    "translations/data/REG_2025_2547_ANNEXIV_OER_54_FIELD_INDEX.csv",
]


def check(ok: bool, message: str) -> None:
    if not ok:
        raise AssertionError(message)


def read_csv(path: str) -> list[dict[str, str]]:
    with (ROOT / path).open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def unique(rows: list[dict[str, str]], keys: list[str]) -> bool:
    tuples = [tuple(row[k] for k in keys) for row in rows]
    return len(tuples) == len(set(tuples))


def main() -> None:
    registry = {r["source_id"]: r for r in read_csv("translations/coverage.csv")}
    gaps = {r["source_id"]: r for r in read_csv("translations/FINAL_SCOPE_AND_GAP_REGISTER.csv")}
    check(len(registry) == len(gaps) == 56, "P1 source inventory count drift")
    check(SRC in registry and SRC in gaps, "2025/2547 source missing")
    check(registry[SRC]["source_sha256"] == P0_SHA, "Original P0 SHA changed")
    check(gaps[SRC]["original_sha256"] == P0_SHA, "Gap register source mismatch")
    check(registry[SRC]["translation_status"] == "PARTIAL_SELECTED_CLAUSES", "Cannot claim complete legal translation")
    check(gaps[SRC]["translation_scope_state"] == "PARTIAL", "Cannot claim completed source")
    check(gaps[SRC]["human_review_status"] == "HUMAN_LEGAL_BILINGUAL_REVIEW_PENDING",
          "Human approval cannot be autogenerated")
    index = (ROOT / "translations/VI_TRANSLATION_MASTER_INDEX.md").read_text(encoding="utf-8")
    content = {}
    for path in DOCS:
        txt = (ROOT / path).read_text(encoding="utf-8")
        content[path] = txt
        check(WATERMARK in txt and P0_SHA in txt, f"{path}: legal watermark/hash missing")
        check(Path(path).name in index, f"{path}: index missing")
        check(path in registry[SRC]["translation_chunk"], f"{path}: coverage missing")
        check(path in gaps[SRC]["translation_file"], f"{path}: gap register missing")
        check("PENDING" in txt or "pending" in txt, f"{path}: no review warning")
    for path in CSVS:
        check(Path(path).name in index, f"{path}: index missing {path}")
        check(path in registry[SRC]["translation_chunk"], f"{path}: coverage missing")
        check(path in gaps[SRC]["translation_file"], f"{path}: gap register missing")

    e = content[DOCS[0]]
    for token in ("E(1)(a)", "E(1)(b)", "E(2)(a)", "E(2)(b)", "E(2)(c)",
                  "E(2)(d)", "E(2)(e)", "E(2)(f)", "E(2)(g)", "E(2)(h)",
                  "E(2)(i)", "E(3)", "E(4)", "F, đoạn 1", "F, đoạn 2", "F, đoạn 3"):
        check(token in e, f"Annex II E/F absent {token}")
    a = content[DOCS[1]]
    for eq in (41, 42, 53, 54, 55, 56, 57, 58, 64):
        check(f"(Equation {eq})" in a, f"Annex III missing equation {eq}")
    check("AttrEm_Dir = DirEm* + Em_H,imp - Em_H,exp + WG_corr,imp - WG_corr,exp - Em_el,prod" in a,
          "Annex III Eq55 sign/ordering changed")
    check("SEE_g(Ck_i) = SEE_g × CK_i" in a, "Clinker Eq64 changed")
    check("RecF = D_Inst / SUM(D_PP)" in a, "Reconciliation Eq41 changed")
    b = content[DOCS[3]]
    for eq in (24, 25, 26, 28):
        check(f"(Equation {eq})" in b, f"PFC/clinker missing Eq{eq}")
    check("OVC × (AEO / CE) × Pr_Al × 0.001" in b, "PFC unit conversion lost")
    check("Corr_eta = 0.667" in a, "Waste gas correction 0.667 lost")
    check("EF_CKD = x / (1 - x)" in b, "CKD non-linear denominator changed")
    check("PFPB MW" in b and "không có số mặc định" in b, "PFC missing factor wrongly filled")

    factors = read_csv(CSVS[0])
    counts = Counter(int(r["table_no"]) for r in factors)
    check(dict(counts) == {1: 40, 2: 11, 3: 9, 4: 3, 5: 9, 6: 3},
          f"Annex II G table row count drift {dict(counts)}")
    check(len(factors) == 75 and unique(factors, ["table_no", "row_no"]),
          "Annex II G rows repeated/missing")
    check(all(r["source_id"] == SRC and r["review_status"].startswith("DRAFT") for r in factors),
          "Factor source or review status changed")
    def factor(table: int, name: str) -> dict[str, str]:
        return next(r for r in factors if int(r["table_no"]) == table and r["source_label_en"] == name)
    for table, name, val, unit in [
        (1, "Natural gas", "56.1", "t_CO2_per_TJ"),
        (1, "Blast furnace gas", "260", "t_CO2_per_TJ"),
        (3, "CaCO3", "0.440", "t_CO2_per_t_material"),
        (5, "Steel / steel scrap", "0.0109", "t_C_per_t_material"),
        (6, "CF4", "6630", "t_CO2e_per_t_gas"),
        (6, "C2F6", "11100", "t_CO2e_per_t_gas"),
        (6, "N2O", "265", "t_CO2e_per_t_gas"),
    ]:
        row = factor(table, name)
        check(row["factor_or_carbon_value"] == val and row["factor_or_carbon_unit"] == unit,
              f"Source factor mutated: table {table}/{name}")

    sector = read_csv(CSVS[1])
    cat = {r["aggregated_goods_category_EN"] for r in sector}
    check(len(sector) == 52 and len(cat) == 19, "Sector OER categories/fields incomplete")
    check(unique(sector, ["category_id", "requirement_id"]), "Duplicate OER sector field")
    for cname in ("Cement", "Crude steel", "Iron or steel products", "Unwrought aluminium", "Aluminium products"):
        check(cname in cat, f"Missing sector {cname}")
    check(any(r["conditional_qualification"].startswith("Only where") for r in sector
              if r["aggregated_goods_category_EN"] == "Unwrought aluminium"),
          "Aluminium alloy threshold >1% condition missing")
    check(any("SOURCE_TEXT_DEFECT" in r["conditional_qualification"] for r in sector),
          "OJ FeNi incomplete source wording not flagged")

    fields = read_csv(CSVS[2])
    n = Counter(r["annex_point"] for r in fields)
    check(dict(n) == {"Annex IV 1.1": 35, "Annex IV 1.1.1": 3, "Annex IV 1.2": 16},
          f"OER primary section counts drift: {n}")
    check(unique(fields, ["annex_point", "field_id"]) and len(fields) == 54,
          "OER field IDs duplicate/missing")
    check(all(r["source_id"] == SRC and r["review_status"] == "DRAFT" for r in fields),
          "OER source or review status corrupted")
    check("bằng tiếng Anh" in content[DOCS[2]], "OER submission-language guard missing")
    print("CBAM A1 STRUCTURAL / ROW PRESERVATION QA PASS: 4 VI documents; 75 Annex II G factors;")
    print("19 sector categories / 52 fields; Annex IV 35+3+16 primary reporting fields; 13 formula IDs.")
    print("SOURCE READING, EN-VI TRANSLATION, UNIT APPLICATION, FORMULA PIXEL PROOF AND LEGAL SIGN-OFF: PENDING.")


if __name__ == "__main__":
    main()
